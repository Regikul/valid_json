%% Контракт загрузчика схем. Загрузчик наполняет хранилище стартовым набором
%% документов: каталогом рядом с релизом, ответом сервиса, выборкой из базы.
%% Нормативное описание — okf/architecture/validator-resources-runtime.md,
%% раздел «Загрузчик схем».
%%
%% Модуль состоит из одной диспетчеризации и знанием о хранилище не обладает:
%% когда звать колбэки и что делать с их ответом, решает управляющий.
-module(valid_json_loader).

-include("valid_json_core.hrl").

-export_type([loader/0]).

%% Загрузчик задаётся модулем и произвольным аргументом. Аргумент приходит из
%% конфигурации разработчика вместе с модулем, поэтому разбирать его здесь не
%% нужно: его понимает тот, кто его же и написал.
-type loader() :: {module(), term()}.

%% Набор возвращается целиком и уходит в один `add`: взаимно ссылающиеся
%% документы обязаны попасть в реестр одним вызовом, иначе первый из них упадёт
%% на неразрешённой ссылке. Имена в наборе относительные — абсолютными их делает
%% база хранилища, и потому один и тот же каталог годится под любой базой.
-callback load(Args :: term()) -> {ok, [{uri(), json()}]} | {error, term()}.

%% База берётся отдельным колбэком, потому что нужна раньше документов: по ней
%% собирается реестр ещё в `init`, а `load/1` вызывается только в
%% `handle_continue`. Ввода-вывода здесь быть не должно.
-callback base_uri(Args :: term()) -> {ok, uri()} | undefined.

